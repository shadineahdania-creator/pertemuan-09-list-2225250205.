nilai = [75, 80, 65]

# Mengubah nilai pada indeks 1 (angka 80 menjadi 82)
nilai[1] = 82 

# Menambahkan angka 90 ke posisi paling akhir list
nilai.append(90) 

# Menyisipkan angka 70 pada indeks 1 (menggeser elemen lainnya ke kanan)
nilai.insert(1, 70) 

# Menghapus angka 65 dari list
nilai.remove(65) 

# Menampilkan hasil akhir list
print(nilai)