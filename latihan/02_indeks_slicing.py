nilai = [75, 80, 65, 90, 88, 70]

# Mengambil elemen pertama (indeks 0)
print(nilai[0]) 

# Mengambil elemen terakhir (indeks -1)
print(nilai[-1]) 

# Mengambil elemen dari awal hingga sebelum indeks 3 (indeks 0, 1, 2)
print(nilai[:3]) 

# Mengambil elemen dari indeks 1 hingga sebelum indeks 4 (indeks 1, 2, 3)
print(nilai[1:4])